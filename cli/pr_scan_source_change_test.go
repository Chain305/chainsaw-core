// TestPRScanSourceChanged: per lockfile kind pr-scan diffs, every direction
// of a source change is ONE row for the dependency — an upgrade from the
// base version, led by origin.source_changed with "source changed: <base> →
// <head>", carrying the head origin (what policy evaluates), and without
// sc.new_dep (it is not a new dependency). A fork added BESIDE a registry
// package that stays is a new dependency, not a change. go.sum has no
// source to change (module paths only) and is not listed. Break it like
// this: return added/upgraded unchanged from markSourceChanges (every case
// comes back as an added row with sc.new_dep and no source reason).
func TestPRScanSourceChanged(t *testing.T) {
	withMirrors(t)
	for _, fx := range sourceFixtures() {
		label := func(src string) string {
			if src == "registry" {
				return "the public registry"
			}
			return fx.labels[src]
		}
		moves := [][2]string{{"registry", "git1"}, {"git1", "registry"}, {"git1", "git2"}}
		if fx.private {
			moves = append(moves, [2]string{"private", "registry"}, [2]string{"registry", "private"})
		}
		for _, mv := range moves {
			t.Run(string(fx.kind)+"/"+mv[0]+"->"+mv[1], func(t *testing.T) {
				added, upgraded, err := diffManifest(fx.kind, "lock", []byte(fx.render(mv[0])), []byte(fx.render(mv[1])))
				if err != nil {
					t.Fatalf("diffManifest: %v", err)
				}
				if len(added) != 0 || len(upgraded) != 1 {
					t.Fatalf("want exactly one upgraded row, got added=%+v upgraded=%+v", added, upgraded)
				}
				raw := upgraded[0]
				want := "source changed: " + label(mv[0]) + " → " + label(mv[1])
				if raw.Name != fx.name || raw.SourceChange != want || raw.PreviousVersion == nil {
					t.Fatalf("row = %+v (source change %q), want %s with %q", raw, raw.SourceChange, fx.name, want)
				}
				if (mv[1] == "registry") != (raw.Origin == "") {
					t.Errorf("row origin %q must be the head's (%s)", raw.Origin, mv[1])
				}
				e := evaluatePREntry(raw)
				ids := map[string]string{}
				for _, s := range e.Signals {
					ids[s.ID] = s.Reason
				}
				if ids[prScanSourceChangedSignalID] != want || e.Verdict == "allow" {
					t.Errorf("entry %+v: want a warn led by %s %q", e, prScanSourceChangedSignalID, want)
				}
				if _, ok := ids["sc.new_dep"]; ok {
					t.Errorf("a changed source is not a new dependency: %+v", e.Signals)
				}
				if e.Origin != "" && e.Signals[0].ID != prScanNotAssessedSignalID {
					t.Errorf("a non-registry row still leads with %s: %+v", prScanNotAssessedSignalID, e.Signals)
				}
			})
		}
	}
}

// TestPRScanForkBesideRegistryIsNew: base has the registry package, head
// keeps it and adds a fork of the same name (Cargo and yarn hold both): the
// fork is a new dependency, not a source change, and the registry row is
// untouched. Break it like this: drop the "head still has this source"
// check in markSourceChanges.
func TestPRScanForkBesideRegistryIsNew(t *testing.T) {
	withMirrors(t)
	for _, fx := range sourceFixtures() {
		if fx.kind != kindCargoLock && fx.kind != kindYarnLock {
			continue
		}
		base := fx.render("registry")
		header := "\n\n\n" // the fork's entry, without its file header
		if fx.kind == kindCargoLock {
			header = "\n\n"
		}
		head := base + "\n" + strings.SplitN(fx.render("git1"), header, 2)[1]
		added, upgraded, err := diffManifest(fx.kind, "lock", []byte(base), []byte(head))
		if err != nil {
			t.Fatalf("%s: %v", fx.kind, err)
		}
		if len(upgraded) != 0 || len(added) != 1 || added[0].Origin == "" || added[0].SourceChange != "" {
			t.Errorf("%s: want one added fork row with no source change, got added=%+v upgraded=%+v", fx.kind, added, upgraded)
		}
	}
}

// TestPRScanPrivateRegistryBumpIsNotASourceChange: a version bump on the same
// private registry moves the tarball URL (the version is in its path), not
// the source. Break it like this: key a registry-other source on its label
// instead of its host in sourceKey.
func TestPRScanPrivateRegistryBumpIsNotASourceChange(t *testing.T) {
	withMirrors(t)
	lock := func(v string) []byte {
		return []byte(`{"name": "app", "version": "1.0.0", "lockfileVersion": 3, "requires": true, "packages": {
  "": {"name": "app", "version": "1.0.0", "dependencies": {"left-pad": "^1.3.0"}},
  "node_modules/left-pad": {"version": "` + v + `", "resolved": "https://npm.corp.example/repository/npm-private/left-pad/-/left-pad-` + v + `.tgz", "integrity": "` + jsSRI + `"}}}`)
	}
	added, upgraded, err := diffManifest(kindNPMPackageLock, "package-lock.json", lock("1.3.0"), lock("1.4.0"))
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range append(added, upgraded...) {
		if e.SourceChange != "" {
			t.Errorf("same private registry, new version: %+v must not be a source change", e)
		}
	}
	if len(added)+len(upgraded) != 1 {
		t.Errorf("want one row, got added=%+v upgraded=%+v", added, upgraded)
	}
}

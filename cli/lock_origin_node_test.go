func jsMalwareIndex() *malware.Index {
	idx := malware.NewIndex(nil)
	var entries []*malware.OSVEntry
	for _, nv := range []string{"lodash@4.17.21", "minimist@1.2.0", "minimist@1.2.8", "strip-ansi@6.0.1", "mirrored@2.0.0", "my-ws@0.0.0"} {
		n, v, _ := strings.Cut(nv, "@")
		entries = append(entries, &malware.OSVEntry{
			ID:       "MAL-TEST-" + n + "-" + v,
			Affected: []malware.OSVAffected{{Package: malware.OSVPackage{Ecosystem: "npm", Name: n}, Versions: []string{v}}},
		})
	}
	idx.Load(entries)
	return idx
}

func setMirrors(t *testing.T, hosts ...any) {
	t.Helper()
	prev := viper.Get("registry_mirrors")
	t.Cleanup(func() { viper.Set("registry_mirrors", prev) })
	viper.Set("registry_mirrors", hosts)
}

func TestGuardJSLockfileOrigins(t *testing.T) {
	for _, tc := range []struct{ file, content string }{
		{"yarn.lock", guardOriginYarnLock},
		{"pnpm-lock.yaml", guardOriginPnpmLock},
	} {
		t.Run(tc.file, func(t *testing.T) {
			dir := guardOriginChdir(t)
			t.Setenv("npm_config_cache", filepath.Join(dir, "npm-cache"))
			setMirrors(t, "nexus.corp")
			if err := os.WriteFile(filepath.Join(dir, tc.file), []byte(tc.content), 0o644); err != nil {
				t.Fatal(err)
			}
			specs := expandLockfile("npm", []string{"install"})
			g := &localGuard{detectors: map[string]*typosquat.Detector{}, malware: jsMalwareIndex()}
			verdicts, blocked := g.evaluateAll(context.Background(), specs)
			if !blocked {
				t.Fatal("registry packages are malicious in the index; the install must be refused")
			}
			gotMal, gotClean, gotNA := map[string]int{}, map[string]int{}, map[string]int{}
			for _, v := range verdicts {
				switch {
				case v.Severity == "malicious":
					gotMal[v.Spec.Name]++
				case v.Severity == "" && !v.Block:
					gotClean[v.Spec.Name]++
				case v.Severity == guardSeverityNotAssessed && strings.Contains(v.Reason, "not from the public registry: not assessed"):
					gotNA[v.Spec.Name]++
					if v.Block {
						t.Errorf("%s: not-assessed must not refuse by default: %+v", v.Spec.Name, v)
					}
					if v.Spec.Name == "internal" && (!strings.Contains(v.Reason, "registry_mirrors") || strings.Contains(v.Reason, "npm-remote")) {
						t.Errorf("undeclared registry: want the registry_mirrors hint and the host only, got %q", v.Reason)
					}
				default:
					t.Errorf("unexpected verdict %+v", v)
				}
			}
			want := map[string]map[string]int{
				// The workspace package is Local: the malware lookup still
				// runs on it (my-ws@0.0.0 is in the index).
				"malicious":    {"lodash": 1, "minimist": 2, "strip-ansi": 1, "mirrored": 1, "my-ws": 1},
				"clean":        {"left-pad": 1},
				"not-assessed": {"left-pad": 1, "internal": 1},
			}
			for what, got := range map[string]map[string]int{"malicious": gotMal, "clean": gotClean, "not-assessed": gotNA} {
				if fmt.Sprint(got) != fmt.Sprint(want[what]) {
					t.Errorf("%s verdicts = %v, want %v (all: %+v)", what, got, want[what], verdicts)
				}
			}
			// Against an EMPTY index only registry specs reach byte acquisition.
			clean := &localGuard{detectors: map[string]*typosquat.Detector{}, malware: malware.NewIndex(nil)}
			cleanVerdicts, _ := clean.evaluateAll(context.Background(), specs)
			for _, v := range cleanVerdicts {
				if v.Spec.Name == "my-ws" {
					t.Errorf("a clean workspace package must say nothing: %+v", v)
				}
			}
			if clean.scanAttempted != 6 {
				t.Errorf("specs reaching byte acquisition = %d, want 6 (registry packages only)", clean.scanAttempted)
			}
		})
	}
}

// TestGuardJSLockfileGitStillRefusesKnownMalware: a git source does not shed
// the malware floor (event-stream 3.3.6 is in it).
func TestGuardJSLockfileGitStillRefusesKnownMalware(t *testing.T) {
	for _, tc := range []struct{ file, content string }{
		{"yarn.lock", "event-stream@evil/event-stream#abc:\n  version \"3.3.6\"\n  resolved \"https://codeload.github.com/evil/event-stream/tar.gz/0123456789abcdef0123456789abcdef01234567\"\n"},
		{"pnpm-lock.yaml", "lockfileVersion: '9.0'\n\npackages:\n\n  event-stream@git+https://github.com/evil/event-stream.git#0123456789abcdef0123456789abcdef01234567:\n    resolution: {commit: 0123456789abcdef0123456789abcdef01234567, repo: https://github.com/evil/event-stream.git, type: git}\n    version: 3.3.6\n"},
	} {
		t.Run(tc.file, func(t *testing.T) {
			dir := guardOriginChdir(t)
			if err := os.WriteFile(filepath.Join(dir, tc.file), []byte(tc.content), 0o644); err != nil {
				t.Fatal(err)
			}
			specs := expandLockfile("npm", []string{"ci"})
			if len(specs) != 1 || specs[0].Origin == "" {
				t.Fatalf("want one non-registry spec, got %+v", specs)
			}
			idx := malware.NewIndex(nil)
			idx.Load(malware.Floor())
			g := &localGuard{detectors: map[string]*typosquat.Detector{}, malware: idx}
			verdicts, blocked := g.evaluateAll(context.Background(), specs)
			if !blocked || len(verdicts) != 1 || verdicts[0].Severity != "malicious" {
				t.Fatalf("a floor package listed from git must still be refused, got blocked=%v %+v", blocked, verdicts)
			}
		})
	}
}

func TestPRScanJSLockfileOrigins(t *testing.T) {
	for _, tc := range []struct {
		kind    manifestKind
		content string
	}{{kindYarnLock, guardOriginYarnLock}, {kindPNPMLock, guardOriginPnpmLock}} {
		t.Run(string(tc.kind), func(t *testing.T) {
			setMirrors(t, "nexus.corp")
			added, upgraded, err := diffManifest(tc.kind, "lock", nil, []byte(tc.content))
			if err != nil || len(upgraded) != 0 {
				t.Fatalf("diffManifest: err=%v upgraded=%v", err, upgraded)
			}
			gotReg, gotNA := map[string]int{}, map[string]int{}
			for _, raw := range added {
				e := evaluatePREntry(raw)
				if e.Origin == "" {
					gotReg[e.Name]++
					continue
				}
				gotNA[e.Name]++
				if e.Verdict == "allow" || e.Signals[0].ID != prScanNotAssessedSignalID {
					t.Errorf("%s: not-assessed row must lead with %s and never allow: %+v", e.Name, prScanNotAssessedSignalID, e)
				}
			}
			wantReg := map[string]int{"lodash": 1, "minimist": 2, "left-pad": 1, "strip-ansi": 1, "mirrored": 1}
			wantNA := map[string]int{"left-pad": 1, "internal": 1}
			if fmt.Sprint(gotReg) != fmt.Sprint(wantReg) || fmt.Sprint(gotNA) != fmt.Sprint(wantNA) {
				t.Errorf("registry rows %v (want %v), not-assessed rows %v (want %v); workspace my-ws must have none", gotReg, wantReg, gotNA, wantNA)
			}
		})
	}
}


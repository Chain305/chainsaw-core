// TestGuardCoverageClosedSkipsNonRegistry: CHAINSAW_COVERAGE_MODE=closed
// refuses registry packages when a required source is unavailable, but no
// coverage source applies to a git or path package: those are not-applicable,
// printed as not assessed, and never refused by the gate.
func TestGuardCoverageClosedSkipsNonRegistry(t *testing.T) {
	guardPolicyTestEnv(t, "")
	t.Setenv("CHAINSAW_GUARD_DB", filepath.Join(t.TempDir(), "none.json"))
	t.Setenv(coverageModeEnv, "closed")
	t.Setenv(coverageRequiredEnv, "cve") // the offline guard can never evaluate CVE data
	git := packageSpec{Ecosystem: "cargo", Name: "etl", Version: "0.1.0", Origin: "git+https://github.com/feldera/etl#cdfb3c7e"}
	reg := packageSpec{Ecosystem: "cargo", Name: "serde", Version: "1.0.197"}

	verdicts, blocked := newLocalGuard().evaluateAll(context.Background(), []packageSpec{git})
	if blocked || len(verdicts) != 1 || verdicts[0].Severity != guardSeverityNotAssessed {
		t.Fatalf("closed coverage must not refuse a non-registry package, got blocked=%v %+v", blocked, verdicts)
	}
	var buf bytes.Buffer
	printGuardVerdicts(&buf, "chainsaw", verdicts, true)
	if !strings.Contains(buf.String(), "not from crates.io: not assessed (github.com/feldera/etl@cdfb3c7)") {
		t.Errorf("not-assessed line not printed under --quiet:\n%s", buf.String())
	}

	verdicts, blocked = newLocalGuard().evaluateAll(context.Background(), []packageSpec{git, reg})
	if !blocked {
		t.Fatal("the registry package must still be refused in closed mode")
	}
	for _, v := range verdicts {
		switch v.Spec.Name {
		case "etl":
			if v.Block || v.Severity != guardSeverityNotAssessed {
				t.Errorf("etl: want not-assessed, not refused: %+v", v)
			}
		case "serde":
			if !v.Block || v.Severity != "coverage" {
				t.Errorf("serde: want a coverage refusal: %+v", v)
			}
		}
	}
}

// TestPRScanCargoMultiVersion: Cargo.lock holds syn 1.x and 2.x side by side.
// Adding the 2.x line is an addition; bumping 1.x is an upgrade of 1.x.
func TestPRScanCargoMultiVersion(t *testing.T) {
	const src = "source = \"registry+https://github.com/rust-lang/crates.io-index\"\n"
	pkg := func(v string) string { return "[[package]]\nname = \"syn\"\nversion = \"" + v + "\"\n" + src + "\n" }
	added, upgraded, err := diffManifest(kindCargoLock, "Cargo.lock", []byte(pkg("1.0.108")), []byte(pkg("1.0.109")+pkg("2.0.66")))
	if err != nil {
		t.Fatal(err)
	}
	if len(added) != 1 || added[0].Version != "2.0.66" {
		t.Errorf("added = %+v, want syn 2.0.66", added)
	}
	if len(upgraded) != 1 || upgraded[0].Version != "1.0.109" || upgraded[0].PreviousVersion == nil || *upgraded[0].PreviousVersion != "1.0.108" {
		t.Errorf("upgraded = %+v, want syn 1.0.108 -> 1.0.109", upgraded)
	}
}

// TestPRScanGitRevMoveIsANewRow: a git dependency whose revision moves keeps
// its version string, but it is different code. Diffing on (name, origin)
// makes it a new not-assessed row instead of nothing.
func TestPRScanGitRevMoveIsANewRow(t *testing.T) {
	lock := func(rev string) []byte {
		return []byte("[[package]]\nname = \"etl\"\nversion = \"0.1.0\"\nsource = \"git+https://github.com/feldera/etl?rev=" + rev + "#" + rev + "\"\n")
	}
	added, upgraded, err := diffManifest(kindCargoLock, "Cargo.lock", lock("aaaaaaaa"), lock("bbbbbbbb"))
	if err != nil || len(upgraded) != 0 {
		t.Fatalf("err=%v upgraded=%v", err, upgraded)
	}
	if len(added) != 1 || added[0].Origin == "" || !strings.Contains(added[0].Origin, "bbbbbbbb") {
		t.Fatalf("a moved git rev must surface as a new non-registry row, got %+v", added)
	}
	if added, _, _ := diffManifest(kindCargoLock, "Cargo.lock", lock("aaaaaaaa"), lock("aaaaaaaa")); len(added) != 0 {
		t.Fatalf("an unchanged git dep must not be a row, got %+v", added)
	}
}


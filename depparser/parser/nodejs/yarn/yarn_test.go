func TestParseV1Origins(t *testing.T) {
	check(t, got(t, v1Lock), []string{
		// Registry, both public aliases: no Origin; every integrity token is
		// in the Hash (npm accepts either, so both must be registry digests).
		"@babel/core@7.22.0 origin= hash=sha1:" + sha1A + " " + hashA,
		"ember-cli-htmlbars@6.3.0 origin= hash=" + hashB,
		// The same name@version from a codeload tarball is a second package.
		"ember-cli-htmlbars@6.3.0 origin=https://codeload.github.com/ember-cli/ember-cli-htmlbars/tar.gz/671b3953f1c7ca5c53cfb84fe49b1cac31764c2a hash=",
		// git: Origin, and the fragment (a commit) is never a Hash.
		"keymaster@1.6.3 origin=https://github.com/madrobby/keymaster.git#f8f43ddafad663b505dc0908e72853bcf8daea49 hash=",
		"private-thing@0.1.0 origin=git+ssh://github.com/acme/private-thing.git#5a6b7c8d9e0f5a6b7c8d9e0f5a6b7c8d9e0f5a6b hash=",
		// A plain tarball URL is non-registry: its integrity is not the registry's.
		"vendored@2.0.0 origin=https://example.com/files/vendored-2.0.0.tgz#" + sha1A + " hash=",
		// A registry-shaped tarball on another host: Origin (sanitized) AND
		// the hash, which is what decides mirror vs private on the server.
		"mirrored@1.0.0 origin=https://artifactory.example.com/artifactory/api/npm/npm-remote/mirrored/-/mirrored-1.0.0.tgz#" + sha1A + " hash=" + hashA,
		// No integrity line (yarn < 1.10): the resolved URL's sha1 is the tarball's.
		"old-style@1.2.0 origin= hash=sha1:" + sha1A,
		// Alias: keyed by the package it installs.
		"string-width@4.2.3 origin= hash=" + hashB,
		// Project-local code: Origin file:<path>, never dropped, never scored.
		"@kbn/actions-plugin@0.0.0 origin=file:x-pack/platform/plugins/shared/actions hash=",
		"local-dir@3.0.0 origin=file:./packages/local-dir hash=",
	})
}


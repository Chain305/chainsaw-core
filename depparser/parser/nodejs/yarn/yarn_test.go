// got renders packages as "name@version origin=<o> hash=<h>", sorted.
func got(t *testing.T, src string) []string {
	t.Helper()
	pkgs, err := Parse(strings.NewReader(src))
	if err != nil {
		t.Fatal(err)
	}
	return render(pkgs)
}

func render(pkgs []ftypes.Package) []string {
	var out []string
	for _, p := range pkgs {
		out = append(out, p.Name+"@"+p.Version+" origin="+p.Origin+" hash="+p.Hash)
	}
	sort.Strings(out)
	return out
}

func check(t *testing.T, got, want []string) {
	t.Helper()
	sort.Strings(want)
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Fatalf("got:\n  %s\nwant:\n  %s", strings.Join(got, "\n  "), strings.Join(want, "\n  "))
	}
}


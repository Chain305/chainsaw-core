// TestParseBerryNoMetadataPackage: the __metadata header used to come out
// as a package "__metadata@8".
func TestParseBerryNoMetadataPackage(t *testing.T) {
	for _, line := range got(t, berryLock) {
		if strings.HasPrefix(line, "__metadata") {
			t.Fatalf("emitted the lockfile header as a package: %s", line)
		}
	}
}

// TestParseV1MultiDescriptorResolvedDecides: a block merging a file:
// descriptor with a range installs the ONE artifact `resolved` names. Red-team
// PoC: the first descriptor was read alone, so a `file:` in front made a
// tarball from any host read as local code (no finding on the server, no
// pr-scan row, Local in the guard).
func TestParseV1MultiDescriptorResolvedDecides(t *testing.T) {
	const lock = `# yarn lockfile v1

"lodash@file:./x", "lodash@^4.17.0":
  version "4.17.21"
  resolved "https://evil.example/lodash/-/lodash-4.17.21.tgz"
  integrity ` + sriA + `

"left@^1.0.0", "left@file:./vendored":
  version "1.0.0"

"both@file:./a", "both@link:./b":
  version "2.0.0"

"tgz@file:./vendor/tgz-1.0.0.tgz", "tgz@^1.0.0":
  version "1.0.0"
  resolved "file:./vendor/tgz-1.0.0.tgz"
`
	check(t, got(t, lock), []string{
		// registry-shaped on another host: Origin plus the hash, decided on the server.
		"lodash@4.17.21 origin=https://evil.example/lodash/-/lodash-4.17.21.tgz hash=" + hashA,
		// no resolved, one descriptor a range: not local code.
		"left@1.0.0 origin= hash=",
		// every descriptor local and nothing resolved: local.
		"both@2.0.0 origin=file:./a hash=",
		// resolved to a file in the project: that path.
		"tgz@1.0.0 origin=file:./vendor/tgz-1.0.0.tgz hash=",
	})
}

// TestParseBerryNoResolutionNonLocalDescriptor: with no resolution the key is
